// ---------------------------------------------------------------------------
// The tailnet policy
//
// Same four grants as the sandbox page, same labels. The sandbox says "first
// matching grant wins"; a real policy is a union of accepts, so the two agree on
// every allow and deny and disagree only on which rule gets the credit. Worth
// knowing before you compare the two side by side.
// ---------------------------------------------------------------------------

type Grant struct {
	Key    string   `json:"key"`
	Src    string   `json:"src"`
	Dst    string   `json:"dst"`
	Ports  []string `json:"ports"`
	Label  string   `json:"label"`
	Sub    string   `json:"sub,omitempty"`
	Danger bool     `json:"danger,omitempty"`
}

var Grants = []Grant{
	{Key: "laptop", Src: "tag:laptop", Dst: "tag:server", Ports: []string{"22"},
		Label: "tag:laptop → tag:server : 22"},
	{Key: "roam", Src: "tag:roam", Dst: "tag:server", Ports: []string{"22"},
		Label: "tag:roam → tag:server : 22"},
	{Key: "untrusted", Src: "tag:untrusted", Dst: "*", Ports: []string{"*"},
		Label: "tag:untrusted → * : *", Danger: true,
		Sub: "one tag, given everything — the over-broad grant"},
	{Key: "any", Src: "*", Dst: "*", Ports: []string{"*"},
		Label: "* → * : *", Danger: true,
		Sub: "membership becomes total access — the default nobody meant to keep"},
}

func (c *Controller) policyHuJSON(acl ACLState) string {
	var rules []string
	add := func(src, dst string, ports []string) {
		var dsts []string
		for _, p := range ports {
			dsts = append(dsts, fmt.Sprintf("%q", dst+":"+p))
		}
		rules = append(rules, fmt.Sprintf(
			"    { \"action\": \"accept\", \"src\": [%q], \"dst\": [%s] }",
			src, strings.Join(dsts, ", ")))
	}
	for _, g := range Grants {
		if acl.Grants[g.Key] {
			add(g.Src, g.Dst, g.Ports)
		}
	}
	if acl.Def == "accept" {
		add("*", "*", []string{"*"})
	}

	ssh := ""
	if acl.SSH {
		ssh = `
  "ssh": [
    {
      "action": "accept",
      "src":    ["tag:laptop", "tag:roam"],
      "dst":    ["tag:server"],
      "users":  ["root", "autogroup:nonroot"],
    },
  ],`
	}

	return fmt.Sprintf(`// Generated by the lab control server. Every line here came from a switch
// you flipped; nothing is decorative.
//
// Default action: %s
{
  "tagOwners": {
    "tag:server":    ["lab@"],
    "tag:laptop":    ["lab@"],
    "tag:roam":      ["lab@"],
    "tag:untrusted": ["lab@"],
  },%s
  "acls": [
%s
  ],
}
`, acl.Def, ssh, strings.Join(rules, ",\n"))
}

// applyPolicy writes the policy and pushes it to the coordination server, which
// distributes it to every node in seconds without anything restarting.
func (c *Controller) applyPolicy(ctx context.Context) error {
	s := c.Snapshot()
	body := c.policyHuJSON(s.ACL)
	path := c.StateFile("policy.hujson")
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		return err
	}
	r, err := c.lab.Exec(ctx, "headscale", "headscale", "policy", "set", "-f", "/lab/state/policy.hujson")
	if err != nil {
		return err
	}
	if r.Code != 0 {
		return fmt.Errorf("headscale policy set: %s", r.Out())
	}
	c.saveDesired()
	return nil
}

func (c *Controller) PolicyText() string {
	return c.policyHuJSON(c.Snapshot().ACL)
}

