func (c *Controller) setLock(ctx context.Context, on bool) Result {
	res := Result{OK: true, Rung: 1, Rule: "tailnet lock (lab equivalent)"}
	c.with(func(s *State) { s.ACL.Lock = on })
	if on {
		res.Why = "No key exists for a machine you did not authorise. A node key on its own " +
			"buys nothing — which is the property tailnet lock gives you on real Tailscale. " +
			"Headscale has no tailnet lock; lab/README.md says what this stands in for."
		if c.lab.Running(ctx, "evil-box") {
			_, _ = c.lab.Exec(ctx, "evil-box", "tailscale", "logout")
			res.Cmds = []string{"tailscale logout   # on evil-box, its key no longer works"}
		}
	} else {
		res.Danger = true
		res.Why = "A reusable key now exists that anybody holding it can join with. That is " +
			"what a leaked key is worth when nothing has to vouch for it."
	}
	c.saveDesired()
	c.Observe(ctx)
	return res
}

func (c *Controller) setExpiry(ctx context.Context, on bool) Result {
	res := Result{Rung: 1, Rule: "key expiry"}
	if on {
		c.with(func(s *State) { s.ACL.Expiry = on })
		c.saveDesired()
		res.OK = true
		res.Why = "Every node in this lab already carries a real expiry — you can read it in " +
			"`headscale nodes list`. Nothing to do."
		res.Cmds = []string{"headscale nodes list -o json | jq '.[].expiry'"}
		return res
	}
	// The honest answer, which is more useful than a switch that lies.
	res.OK = false
	res.Rung = 0
	res.Rule = "Headscale has no per-node 'disable key expiry'"
	res.Why = "The sandbox can switch this off because it is a model. This lab cannot, " +
		"because Headscale does not expose it — and a real stack refusing to be made " +
		"unsafe the way the model says is exactly the kind of gap this pair exists to " +
		"find. The audit reads the real expiry either way, so the score stays honest."
	return res
}

