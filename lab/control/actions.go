func (c *Controller) setLink(ctx context.Context, id string, up bool) Result {
	res := Result{Rung: 1, Rule: id + " eth0"}
	state := "down"
	if up {
		state = "up"
	}
	res.Cmds = []string{"ip link set eth0 " + state + "   # on " + id}
	r, err := c.lab.Exec(ctx, id, "ip", "link", "set", "eth0", state)
	res.Raw = r.Out()
	if err != nil {
		res.Why = err.Error()
		return res
	}
	res.OK = true
	if up {
		// Taking an interface down drops every route through it, including the
		// one pointing at this machine's NAT router. The kernel puts back the
		// on-link route and nothing else, so without this the machine comes
		// back with a working cable and nowhere to send anything.
		if gw := c.gatewayFor(id); gw != "" {
			rr, _ := c.lab.Exec(ctx, id, "ip", "route", "replace", "default", "via", gw)
			res.Raw += "\n" + rr.Out()
			res.Cmds = append(res.Cmds, "ip route replace default via "+gw+"   # on "+id)
		}
		res.Why = "eth0 is back. Watch what reconnects on its own and what does not."
	} else {
		res.Why = "eth0 is down on " + id + " — nothing leaves the machine. " +
			"This is the tunnel, and it is the whole reason chapter 03 exists."
	}
	c.observeLinks(ctx)
	return res
}

func (c *Controller) shape(ctx context.Context, id string, loss, delay int) Result {
	res := Result{Rung: 2, Rule: "tc netem on " + id}
	_, _ = c.lab.Sh(ctx, id, "tc qdisc del dev eth0 root 2>/dev/null || true")
	if loss == 0 && delay == 0 {
		res.OK = true
		res.Cmds = []string{"tc qdisc del dev eth0 root   # on " + id}
		res.Why = "the link is clean again"
		c.observeLinks(ctx)
		return res
	}
	cmd := "tc qdisc add dev eth0 root netem"
	if loss > 0 {
		cmd += fmt.Sprintf(" loss %d%%", loss)
	}
	if delay > 0 {
		cmd += fmt.Sprintf(" delay %dms %dms", delay, delay/4)
	}
	res.Cmds = []string{cmd + "   # on " + id}
	r, err := c.lab.Sh(ctx, id, cmd)
	res.Raw = r.Out()
	if err != nil || r.Code != 0 {
		res.Why = "tc refused: " + r.Out()
		return res
	}
	res.OK = true
	res.LossPct = float64(loss)
	res.Why = fmt.Sprintf("%s now loses %d%% of packets and adds %dms — a bad café, on purpose", id, loss, delay)
	c.observeLinks(ctx)
	return res
}

func (c *Controller) blockUDP(ctx context.Context, id string, block bool) Result {
	res := Result{Rung: 2, Rule: "udp/41641 on " + id}
	if block {
		script := strings.Join([]string{
			"nft add table inet lab",
			"nft 'add chain inet lab out { type filter hook output priority 0 ; }'",
			"nft add rule inet lab out udp dport 41641 drop",
			"nft add rule inet lab out udp sport 41641 drop",
		}, " && ")
		res.Cmds = []string{
			"nft add table inet lab",
			"nft add chain inet lab out { type filter hook output priority 0 \\; }",
			"nft add rule inet lab out udp dport 41641 drop",
			"nft add rule inet lab out udp sport 41641 drop",
		}
		r, err := c.lab.Sh(ctx, id, script)
		res.Raw = r.Out()
		if err != nil || r.Code != 0 {
			res.Why = "nft refused: " + r.Out()
			return res
		}
		res.OK = true
		res.Why = "WireGuard's UDP port is dropped on " + id + ". Give it a few seconds and " +
			"the session should reappear over DERP, on TCP 443 — watch the path chip change."
	} else {
		res.Cmds = []string{"nft delete table inet lab"}
		r, _ := c.lab.Sh(ctx, id, "nft delete table inet lab 2>/dev/null || true")
		res.Raw = r.Out()
		res.OK = true
		res.Why = "UDP is allowed again; the direct path should come back on its own"
	}
	c.observeLinks(ctx)
	return res
}

// ---------------------------------------------------------------------------
// Tailnet lock and key expiry — the two places Headscale is not Tailscale
// ---------------------------------------------------------------------------

func (c *Controller) setLock(ctx context.Context, on bool) Result {
	res := Result{OK: true, Rung: 1, Rule: "tailnet lock (lab equivalent)"}
	c.with(func(s *State) { s.ACL.Lock = on })
	if on {
		res.Why = "No key exists for a machine you did not authorise. A node key on its own " +
			"buys nothing — which is the property tailnet lock gives you on real Tailscale. " +
			"Headscale has no tailnet lock; lab/README.md says what this stands in for."
		if c.lab.Running(ctx, "evil-box") {
			_, _ = c.lab.Exec(ctx, "evil-box", "tailscale", "logout")
			res.Cmds = []string{"tailscale logout   # on evil-box, its key no longer works"}
		}
	} else {
		res.Danger = true
		res.Why = "A reusable key now exists that anybody holding it can join with. That is " +
			"what a leaked key is worth when nothing has to vouch for it."
	}
	c.saveDesired()
	c.Observe(ctx)
	return res
}

func (c *Controller) setExpiry(ctx context.Context, on bool) Result {
	res := Result{Rung: 1, Rule: "key expiry"}
	if on {
		c.with(func(s *State) { s.ACL.Expiry = on })
		c.saveDesired()
		res.OK = true
		res.Why = "Every node in this lab already carries a real expiry, 180 days from the " +
			"moment it registered — the control server stamps it on once the machine has " +
			"joined, and you can read it back in `headscale nodes list`. Nothing to do. " +
			"(`node.expiry` in config/headscale/config.yaml does not do this on its own: " +
			"Headscale 0.29 honours it for a single-use pre-auth key and ignores it for " +
			"the reusable one these three machines share.)"
		res.Cmds = []string{"headscale nodes list -o json | jq '.[].expiry'"}
		return res
	}
	// The honest answer, which is more useful than a switch that lies.
	res.OK = false
	res.Rung = 0
	res.Rule = "Headscale has no per-node 'disable key expiry'"
	res.Why = "The sandbox can switch this off because it is a model. This lab cannot: " +
		"`node.expiry` applies to every registration and Headscale has no per-node way to " +
		"undo it — and a real stack refusing to be made unsafe the way the model says is " +
		"exactly the kind of gap this pair exists to find. It is also why `day-one`, " +
		"`typical` and `weak` score a point here that the sandbox does not give them; the " +
		"audit marks that check rather than letting the configuration take the credit."
	return res
}

