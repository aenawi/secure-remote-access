// ApplyPreset drives the whole stack into one of the four named states. The ids
// are the sandbox's ids, and `docker compose --profile weak up` runs exactly
// this.
func (c *Controller) ApplyPreset(ctx context.Context, id string) Result {
	c.loadDesired()
	p, ok := presetByID(id)
	if !ok {
		return Result{Why: "no configuration called " + id}
	}
	res := Result{OK: true, Rung: 0, Rule: p.Label, Why: p.Note}

	c.with(func(s *State) {
		s.ACL = p.ACL
		s.ACL.Grants = map[string]bool{}
		for k, v := range p.ACL.Grants {
			s.ACL.Grants[k] = v
		}
	})
	if err := c.applyPolicy(ctx); err != nil {
		res.Raw += "policy: " + err.Error() + "\n"
	}
	res.Cmds = append(res.Cmds, "headscale policy set -f policy.hujson")

	for _, m := range []string{"lab-vps", "lab-ubuntu", "lab-roam"} {
		if !c.lab.Running(ctx, m) {
			continue
		}
		if p.Tailnet {
			_, _ = c.lab.Sh(ctx, m, `tailscale status --json | grep -q '"BackendState": *"Running"' || tailscale up --login-server=https://headscale:8443 --authkey="$(cat /lab/state/authkey)" --hostname=`+m+` --accept-routes=false --accept-dns=false --timeout=30s`)
		} else {
			_, _ = c.lab.Exec(ctx, m, "tailscale", "down")
		}
	}
	if !p.Tailnet {
		res.Cmds = append(res.Cmds, "tailscale down   # day one: the box has never heard of a tailnet")
	}

	for _, step := range []struct {
		path string
		val  any
	}{
		{"vps.ufwDefaultDeny", p.VPS.UFWDefaultDeny},
		{"vps.allowTailscale0", p.VPS.AllowTailscale},
		{"vps.allowPublic22", p.VPS.AllowPublic22},
		{"vps.dockerPublish", p.VPS.DockerPublish},
		{"vps.passwordAuth", p.VPS.PasswordAuth},
		{"vps.permitRoot", p.VPS.PermitRoot},
		{"vps.sshdListen", p.VPS.SSHDListen},
	} {
		r := c.Set(ctx, step.path, step.val)
		res.Cmds = append(res.Cmds, r.Cmds...)
	}

	c.with(func(s *State) { s.ACL.Lock = p.ACL.Lock })
	_ = c.setLock(ctx, p.ACL.Lock)

	// A named configuration is a configuration, not a configuration plus
	// whatever somebody left running on the side. None of the four says
	// anything about tailcat — it is not in the build order and chapter 11
	// keeps it out on purpose — so loading one takes the tunnel down rather
	// than scoring a stack with an extra way in nobody asked for.
	_ = c.tailcatStopAll(ctx)
	c.with(func(s *State) {
		s.Tailcat = TailcatState{Host: defaultState().Tailcat.Host,
			Service: defaultState().Tailcat.Service}
	})
	if c.lab.Running(ctx, "evil-box") {
		_, _ = c.lab.Sh(ctx, "evil-box", "rm -f "+tailcatSharedFile)
	}
	res.Cmds = append(res.Cmds, "pkill -f "+tailcatPattern+"   # a configuration is not a "+
		"configuration plus a tunnel somebody left up")
	c.saveDesired()

	c.Observe(ctx)
	return res
}

// Reset puts everything back: clean links, no attacker, the boot configuration.
func (c *Controller) Reset(ctx context.Context) Result {
	res := Result{OK: true, Rule: "reset", Cmds: []string{"make reset   # for the harder version of this"}}
	for _, m := range Catalog {
		if !c.lab.Running(ctx, m.ID) {
			continue
		}
		restore := "tc qdisc del dev eth0 root 2>/dev/null; nft delete table inet lab 2>/dev/null; ip link set eth0 up"
		if gw := c.gatewayFor(m.ID); gw != "" {
			restore += "; ip route replace default via " + gw
		}
		_, _ = c.lab.Sh(ctx, m.ID, restore)
	}
	if c.lab.Running(ctx, "evil-box") {
		_, _ = c.lab.Exec(ctx, "evil-box", "tailscale", "logout")
		_, _ = c.lab.Exec(ctx, "evil-box", "lab-onpath", "off")
		_, _ = c.lab.Sh(ctx, "evil-box", "rm -f "+tailcatSharedFile)
	}
	// The escape hatch closes here too. It is the one thing in the lab that
	// leaves a process running on a machine you own, and a reset that left it
	// up would be the reset that matters least and misleads most.
	_ = c.tailcatStopAll(ctx)
	if c.lab.Running(ctx, "lab-ubuntu") {
		_, _ = c.lab.Exec(ctx, "lab-ubuntu", "ip", "route", "replace", "default", "via", c.gatewayFor("lab-ubuntu"))
	}

	// Put the three machines back on the tailnet. The `day-one` configuration
	// takes them off it deliberately, and without this there is no way back to
	// the boot state except loading another configuration — which is not what a
	// button called "Reset everything" should mean.
	for _, m := range []string{"lab-vps", "lab-ubuntu", "lab-roam"} {
		if !c.lab.Running(ctx, m) {
			continue
		}
		_, _ = c.lab.Sh(ctx, m, `tailscale status --json | grep -q '"BackendState": *"Running"' || `+
			`tailscale up --login-server=https://headscale:8443 --authkey="$(cat /lab/state/authkey)" `+
			`--hostname=`+m+` --accept-routes=false --accept-dns=false --timeout=30s`)
	}
	res.Cmds = append(res.Cmds, "tailscale up --login-server=…   # on any machine that was taken off")

	d := defaultState()
	c.with(func(s *State) { s.ACL = d.ACL; s.Tailcat = d.Tailcat })
	_ = c.applyPolicy(ctx)
	for _, step := range []struct {
		path string
		val  any
	}{
		{"vps.ufwDefaultDeny", true}, {"vps.allowTailscale0", true},
		{"vps.allowPublic22", true}, {"vps.dockerPublish", false},
		{"vps.passwordAuth", false}, {"vps.permitRoot", false},
		{"vps.sshdListen", "all"},
	} {
		_ = c.Set(ctx, step.path, step.val)
	}
	res.Why = "Links clean, attacker logged out, the boot configuration back. " +
		"`make reset` goes further and throws the containers away."
	c.Observe(ctx)
	return res
}

