var errUnknownPath = fmt.Errorf("unknown switch")

func (c *Controller) Set(ctx context.Context, path string, value any) Result {
	// Start from the shared truth, not from whatever this process last thought.
	// `docker compose --profile weak up` is a different process; without this,
	// the first thing the long-running server does after it is to push its own
	// stale policy over the one that was just applied.
	c.loadDesired()
	res := Result{OK: true, Rung: 0, Rule: path}

	boolOf := func() bool {
		switch v := value.(type) {
		case bool:
			return v
		case string:
			return v == "true" || v == "on"
		case float64:
			return v != 0
		}
		return false
	}
	strOf := func() string {
		if s, ok := value.(string); ok {
			return s
		}
		return fmt.Sprint(value)
	}
	intOf := func() int {
		switch v := value.(type) {
		case float64:
			return int(v)
		case string:
			n, _ := strconv.Atoi(v)
			return n
		}
		return 0
	}

	switch {
	// ---- machines -------------------------------------------------------
	case strings.HasPrefix(path, "machines.") && strings.HasSuffix(path, ".online"):
		id := strings.TrimSuffix(strings.TrimPrefix(path, "machines."), ".online")
		return c.setOnline(ctx, id, boolOf())

	case path == "machines.evil-box.onTailnet":
		return c.evilJoin(ctx, boolOf())

	case path == "machines.evil-box.signed":
		// See lab/README.md: Headscale has no tailnet lock, so "signed" here
		// means the operator deliberately handed this machine a key.
		return c.evilJoin(ctx, boolOf())

	case path == "segmentShared":
		return c.setOnPath(ctx, boolOf())

	// ---- the network ----------------------------------------------------
	case strings.HasPrefix(path, "links.") && strings.HasSuffix(path, ".up"):
		id := strings.TrimSuffix(strings.TrimPrefix(path, "links."), ".up")
		return c.setLink(ctx, id, boolOf())

	case strings.HasPrefix(path, "links.") && strings.HasSuffix(path, ".loss"):
		id := strings.TrimSuffix(strings.TrimPrefix(path, "links."), ".loss")
		st := c.Snapshot()
		return c.shape(ctx, id, intOf(), st.Links[id].Delay)

	case strings.HasPrefix(path, "links.") && strings.HasSuffix(path, ".delay"):
		id := strings.TrimSuffix(strings.TrimPrefix(path, "links."), ".delay")
		st := c.Snapshot()
		return c.shape(ctx, id, st.Links[id].Loss, intOf())

	case strings.HasPrefix(path, "links.") && strings.HasSuffix(path, ".udpBlocked"):
		id := strings.TrimSuffix(strings.TrimPrefix(path, "links."), ".udpBlocked")
		return c.blockUDP(ctx, id, boolOf())

	// ---- tailnet policy -------------------------------------------------
	case path == "acl.def":
		c.with(func(s *State) { s.ACL.Def = strOf() })
		return c.pushPolicy(ctx, res, "policy default action -> "+strOf())

	case strings.HasPrefix(path, "acl.grants."):
		k := strings.TrimPrefix(path, "acl.grants.")
		v := boolOf()
		c.with(func(s *State) { s.ACL.Grants[k] = v })
		return c.pushPolicy(ctx, res, "grant "+k+" -> "+strconv.FormatBool(v))

	case path == "acl.ssh":
		v := boolOf()
		c.with(func(s *State) { s.ACL.SSH = v })
		out := c.pushPolicy(ctx, res, "tailscale ssh -> "+strconv.FormatBool(v))
		for _, id := range []string{"lab-vps", "lab-ubuntu", "lab-roam"} {
			arg := "--ssh=false"
			if v {
				arg = "--ssh"
			}
			_, _ = c.lab.Exec(ctx, id, "tailscale", "set", arg)
		}
		out.Cmds = append(out.Cmds, "tailscale set --ssh"+map[bool]string{true: "", false: "=false"}[v])
		return out

	case path == "acl.lock":
		return c.setLock(ctx, boolOf())

	case path == "acl.expiry":
		return c.setExpiry(ctx, boolOf())

	// ---- the host -------------------------------------------------------
	case path == "vps.ufwDefaultDeny":
		return c.ufw(ctx, boolOf(),
			[]string{"ufw", "default", "deny", "incoming"},
			[]string{"ufw", "default", "allow", "incoming"})

	case path == "vps.allowTailscale0":
		return c.ufw(ctx, boolOf(),
			[]string{"ufw", "allow", "in", "on", "tailscale0"},
			[]string{"ufw", "--force", "delete", "allow", "in", "on", "tailscale0"})

	case path == "vps.allowPublic22":
		return c.ufw(ctx, boolOf(),
			[]string{"ufw", "allow", "22/tcp"},
			[]string{"ufw", "--force", "delete", "allow", "22/tcp"})

	case path == "vps.dockerPublish":
		return c.dockerTrap(ctx, boolOf())

	case path == "vps.sshdListen":
		return c.sshdListen(ctx, strOf())

	case path == "vps.passwordAuth":
		return c.sshdOption(ctx, "PasswordAuthentication", map[bool]string{true: "yes", false: "no"}[boolOf()])

	case path == "vps.permitRoot":
		return c.sshdOption(ctx, "PermitRootLogin", map[bool]string{true: "yes", false: "prohibit-password"}[boolOf()])
	}

	res.OK = false
	res.Why = errUnknownPath.Error() + ": " + path
	return res
}

func (c *Controller) pushPolicy(ctx context.Context, res Result, what string) Result {
	res.Cmds = append(res.Cmds, "headscale policy set -f policy.hujson   # "+what)
	if err := c.applyPolicy(ctx); err != nil {
		res.OK = false
		res.Why = err.Error()
		return res
	}
	res.Why = "policy updated and pushed to every node"
	return res
}

