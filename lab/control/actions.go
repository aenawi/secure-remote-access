func (c *Controller) ufw(ctx context.Context, on bool, add, del []string) Result {
	argv := add
	if !on {
		argv = del
	}
	res := Result{Rung: 4, Rule: strings.Join(argv, " "), Cmds: []string{"sudo " + strings.Join(argv, " ") + "   # on lab-vps"}}
	r, err := c.lab.Exec(ctx, "lab-vps", argv...)
	res.Raw = r.Out()
	if err != nil {
		res.Why = err.Error()
		return res
	}
	res.OK = r.Code == 0
	if !res.OK {
		res.Why = "ufw refused: " + r.Out()
	} else {
		res.Why = "ufw updated. Read the rules tab, then probe — the two do not always agree, " +
			"and the times they do not are the interesting ones."
	}
	c.observeVPS(ctx)
	return res
}

func (c *Controller) dockerTrap(ctx context.Context, on bool) Result {
	arg := "off"
	if on {
		arg = "on"
	}
	res := Result{Rung: 4, Rule: "DOCKER-USER / DOCKER chains on lab-vps"}
	res.Cmds = []string{"lab-docker-trap " + arg + "   # on lab-vps: the rules dockerd writes"}
	r, err := c.lab.Exec(ctx, "lab-vps", "lab-docker-trap", arg)
	res.Raw = r.Out()
	if err != nil || r.Code != 0 {
		res.Why = "the trap could not be set: " + r.Out()
		return res
	}
	res.OK = true
	res.Danger = on
	if on {
		res.Why = "Port 8080 now forwards to a container, through chains that sit ahead of " +
			"ufw's. ufw will still tell you the default policy is deny."
	} else {
		res.Why = "the published port is gone"
	}
	c.observeVPS(ctx)
	return res
}

// sshdConf is the one file the lab rewrites. It has to be one file, and every
// setting has to live in it, because sshd takes the FIRST value it finds for a
// keyword across the whole of sshd_config.d — so dropping a second file later in
// the sort order changes nothing at all, silently, and the switch looks broken.
const sshdConf = "/etc/ssh/sshd_config.d/10-lab-runtime.conf"

func sshdRewrite(key, value string) string {
	return fmt.Sprintf(
		`touch %[1]s; sed -i '/^%[2]s /d' %[1]s; printf '%%s %%s\n' '%[2]s' '%[3]s' >> %[1]s; `+
			`pkill sshd; sleep 1; /usr/sbin/sshd`, sshdConf, key, value)
}

func (c *Controller) sshdListen(ctx context.Context, mode string) Result {
	res := Result{Rung: 5, Rule: "sshd ListenAddress"}
	addr := "0.0.0.0"
	if mode == "tailnet" {
		addr = c.tsAddr(ctx, "lab-vps")
		if addr == "" {
			res.Why = "lab-vps has no tailnet address yet, so there is nothing to bind to"
			return res
		}
	}
	res.Cmds = []string{
		"sed -i 's/^ListenAddress.*/ListenAddress " + addr + "/' /etc/ssh/sshd_config",
		"systemctl restart ssh",
	}
	r, err := c.lab.Sh(ctx, "lab-vps", sshdRewrite("ListenAddress", addr)+
		"; ss -tlnp 2>/dev/null | head -4")
	res.Raw = r.Out()
	if err != nil {
		res.Why = err.Error()
		return res
	}
	res.OK = true
	if mode == "tailnet" {
		res.Why = "sshd is bound to " + addr + " only. A packet arriving on eth0 will now be " +
			"permitted by every firewall and answered by nothing — that is a rung-5 failure, " +
			"and no rule you can read explains it."
	} else {
		res.Why = "sshd is back on 0.0.0.0 and answers on every interface"
	}
	c.observeVPS(ctx)
	return res
}

func (c *Controller) sshdOption(ctx context.Context, key, value string) Result {
	res := Result{Rung: 5, Rule: key + " " + value}
	res.Cmds = []string{
		fmt.Sprintf("sed -i 's/^#\\?%s.*/%s %s/' /etc/ssh/sshd_config", key, key, value),
		"systemctl reload ssh",
	}
	r, err := c.lab.Sh(ctx, "lab-vps", sshdRewrite(key, value)+
		fmt.Sprintf("; sshd -T 2>/dev/null | grep -i '^%s'", strings.ToLower(key)))
	res.Raw = r.Out()
	if err != nil {
		res.Why = err.Error()
		return res
	}
	res.OK = true
	res.Danger = value == "yes"
	res.Why = "sshd now reports: " + strings.TrimSpace(r.Stdout)
	c.observeVPS(ctx)
	return res
}

// ---------------------------------------------------------------------------
// The probe — the five-rung ladder, walked against real kernels
//
// The sandbox works the rung out from its model. This works it out from
// evidence: it watches the destination while the source connects. If nothing
// arrives, the tailnet refused it and the far machine never heard about it
// (rung 3). If something arrives and dies, the host firewall dropped it
// (rung 4). If something arrives and is refused, nothing was listening
// (rung 5). That asymmetry is chapter 14's callout, and here it is measured
// rather than asserted.
// ---------------------------------------------------------------------------

// noPeerInNetmap is what the ladder says when both ends hold a tailnet session
// and the far machine is not in the near one's netmap at all. It is a rung-3
// denial with a distinguishing feature: the policy removed the peer rather than
// dropping its packets, so there is nothing to capture on the far machine and
// no log line to go looking for. Saying that out loud is the whole point —
// "nothing arrived and nothing was logged" is the denial people misread as a
// broken network.
func noPeerInNetmap(from, to string) Result {
	return Result{
		From: from, To: to, Rung: 3, Path: "direct",
		Rule: "the tailnet policy refused it — " + to + " is not even in " + from + "'s netmap",
		Why: "Nothing reached " + to + ", and " + from + " cannot see that it exists. " +
			"The policy removed the peer rather than dropping its packets, so there is " +
			"no log line on " + to + " to find.",
		Cmds: []string{"tailscale status   # on " + from + ": " + to + " is absent"},
	}
}

// tailnetPath reads `tailscale ping`'s output and says which way this pair
// settled on. The answer is the last line that reported a pong, not the last
// line: ping prints a summary underneath ("direct connection not established")
// and reading that as the verdict turns every relayed session into no session
// at all. ok is false when nothing ponged, which is a pair with two sessions
// and no path between them — rung 2, and a different finding from a policy
// denial.
func tailnetPath(pingOut string) (path, rule, why string, ok bool) {
	pong := lastLineContaining(pingOut, "pong from")
	switch {
	case strings.Contains(pong, "via DERP"):
		return "relay", "relayed through DERP — no direct path was available: " + pong, "", true
	case pong != "":
		return "direct", "direct — both NATs held a mapping open and the punch completed: " + pong, "", true
	default:
		r := lastLine(pingOut)
		return "", r, "Both ends have a tailnet session and no path between them: " + r, false
	}
}

// knock is the evidence one connection attempt produced, at both of its ends:
// what `nc -vz` said where it started, and what `tcpdump` caught where it was
// aimed. Rungs 3, 4 and 5 are a pure function of those two strings plus the
// interface the capture was watching, and keeping it a pure function is the
// only reason the ladder can be tested without a tailnet, a kernel or a
// container.
//
// The asymmetry it encodes is chapter 14's callout and the reason the lab
// exists. Nothing arrived → the tailnet refused it and the far machine was
// never involved. It arrived and died quietly → the host firewall dropped it,
// and that one is visible on the machine. It arrived and was refused → every
// rule permitted it and nothing was listening, which is usually a bind address
// rather than a rule.
type knock struct {
	from, to   string
	iface      string // the interface tcpdump was watching on `to`
	addr, port string
	out        string // `nc -vz -w 4 <addr> <port> 2>&1; echo "rc=$?"`
	capture    string // tcpdump's line, or empty if nothing arrived
}

// reached is nc's own exit status, which is the only thing that settles whether
// the connection completed. The banner it prints on success is not always the
// same sentence across nc implementations; the return code is.
func (k knock) reached() bool { return strings.Contains(k.out, "rc=0") }

func (k knock) refused() bool { return strings.Contains(strings.ToLower(k.out), "refused") }

// arrived asks the far machine, not the near one. This is the measurement that
// separates a rung-3 denial from a rung-4 one, and there is no way to make it
// from the sending side.
func (k knock) arrived() bool { return strings.TrimSpace(k.capture) != "" }

func (k knock) classify() (rung int, ok bool, rule, why string) {
	if k.reached() {
		return 5, true, "", "reached " + k.addr + ":" + k.port
	}
	if !k.arrived() {
		// Nothing turned up at the far end. Over the tailnet that is the
		// policy; over the ordinary network it means there is no path at all,
		// which is a claim about routing rather than about rules.
		if k.iface == "tailscale0" {
			return 3, false, "the tailnet policy refused it",
				"Nothing reached " + k.to + ". The tailnet dropped it before the far " +
					"machine was involved, so there is no log line on " + k.to + " to find — " +
					"which is exactly how a rung-3 denial feels when you are debugging one."
		}
		return 2, false, "",
			"Nothing arrived at " + k.to + " at all. There is no path between " +
				"these two right now."
	}
	if k.refused() {
		return 5, false, "the firewall permitted it — that is not the same as an answer",
			"The packet arrived and was refused. Every rule allowed it and nothing " +
				"was listening on an address this path reaches. Usually a bind address, " +
				"not a rule."
	}
	return 4, false, "the host firewall dropped it",
		"The packet reached " + k.to + " — you can see it in the capture — and the " +
			"box dropped it. Unlike a rung-3 denial, this one is visible on the machine."
}

var rttRe = regexp.MustCompile(`= [\d.]+/([\d.]+)/`)
var lossRe = regexp.MustCompile(`([\d.]+)% packet loss`)

func (c *Controller) Probe(ctx context.Context, from, to, port string) Result {
	c.loadDesired()
	res := Result{From: from, To: to, Port: port, Rung: 1}

	fm, ok1 := machineByID(from)
	tm, ok2 := machineByID(to)
	if !ok1 || !ok2 {
		res.Why = "no such machine"
		return res
	}
	_ = fm

	// ---- rung 1 · is anything alive? -----------------------------------
	if !c.lab.Running(ctx, from) {
		res.Why = from + " is not running"
		return res
	}
	if !c.lab.Running(ctx, to) {
		res.Why = to + " is not running"
		return res
	}
	fromST, _ := c.tailscaleStatus(ctx, from)
	toST, _ := c.tailscaleStatus(ctx, to)
	fromOn := fromST.BackendState == "Running"
	toOn := toST.BackendState == "Running"

	// ---- rung 2 · which way, if any? ------------------------------------
	res.Rung = 2
	var addr, iface string
	if fromOn && toOn {
		for _, p := range fromST.Peer {
			if p.HostName == to && len(p.TailAddr) > 0 {
				addr = p.TailAddr[0]
			}
		}
		iface = "tailscale0"
		if addr == "" {
			// Both ends have a session and the far machine is not in this
			// one's netmap at all. That is the policy at its most complete: a
			// peer you may not talk to is not merely blocked, it is not sent to
			// you. Rung 3, and there is nothing on the far machine to look at.
			r := noPeerInNetmap(from, to)
			r.Port = port
			return r
		}
	}
	if addr != "" {
		// `tailscale status` reports the path a session is *currently* using,
		// and a pair that has not spoken yet has no session at all — which
		// reads as "relay" when the truth is "nothing has tried". Ask the thing
		// whose whole job is to answer this instead. It keeps trying until it
		// gets a direct path or runs out of attempts, so what comes back is the
		// path this pair settles on rather than the first packet's fate.
		pr, _ := c.lab.Exec(ctx, from, "tailscale", "ping", "--c", "5", "--timeout", "8s", addr)
		// The last line is a summary ("direct connection not established"), so
		// the answer is the last line that actually reported a pong.
		path, rule, why, settled := tailnetPath(pr.Out())
		res.Path, res.Rule = path, rule
		if !settled {
			res.Why = why
			return res
		}
	}
	if addr == "" {
		// Not both on the tailnet: what is left is the ordinary network, and on
		// the ordinary network only lab-vps has an address anyone can reach.
		if to != "lab-vps" {
			res.Why = to + " is behind its own NAT and has no address the ordinary network " +
				"can reach. Without a tailnet there is no path at all — which is the thing " +
				"the tailnet is for."
			return res
		}
		addr = c.lab.IPOn(ctx, "lab-vps", "wan")
		res.Path = "public"
		res.Rule = "over the segment standing in for the public internet, to whatever answers"
		iface = c.ifaceOn(ctx, "lab-vps", addr)
	}
	if addr == "" {
		res.Why = "no address to aim at"
		return res
	}
	if res.Path == "" {
		res.Path = "relay"
		res.Rule = "a tailnet session exists but no path has settled yet"
	}

	// ---- rungs 3, 4 and 5 · watch the far end while we knock ------------
	capFile := "/tmp/probe-" + port + ".txt"
	_, _ = c.lab.Sh(ctx, to, fmt.Sprintf(
		`rm -f %s; (timeout 8 tcpdump -l -n -i %s -c 1 'tcp dst port %s' > %s 2>/dev/null &) ; sleep 1`,
		capFile, iface, port, capFile))

	ncr, _ := c.lab.Sh(ctx, from, fmt.Sprintf(
		`nc -vz -w 4 %s %s 2>&1; echo "rc=$?"`, addr, port))

	time.Sleep(700 * time.Millisecond)
	capr, _ := c.lab.Sh(ctx, to, "cat "+capFile+" 2>/dev/null; rm -f "+capFile)

	k := knock{from: from, to: to, iface: iface, addr: addr, port: port,
		out: ncr.Out(), capture: capr.Stdout}

	res.Cmds = []string{
		fmt.Sprintf("tcpdump -n -i %s -c 1 'tcp dst port %s'   # on %s", iface, port, to),
		fmt.Sprintf("nc -vz -w 4 %s %s   # on %s", addr, port, from),
	}
	res.Raw = strings.TrimSpace(k.out)
	if k.arrived() {
		res.Raw += "\n\n" + to + " saw it arrive:\n" + strings.TrimSpace(k.capture)
	} else {
		res.Raw += "\n\n" + to + " saw nothing arrive on " + iface + "."
	}

	rung, ok, rule, why := k.classify()
	res.Rung, res.OK, res.Why = rung, ok, why
	if rule != "" {
		res.Rule = rule
	}
	if !ok {
		return res
	}

	// ---- it worked. Now the numbers, measured rather than modelled. -----
	if tm.ID == "lab-vps" && port == "8080" {
		s := c.Snapshot()
		if s.VPS.UFWDefaultDeny && res.Path == "public" {
			res.Danger = true
			res.Rule = "DOCKER-USER accepted it before ufw's chain ever ran"
		}
	}

	if p, err := c.lab.Sh(ctx, from, fmt.Sprintf("ping -c 5 -W 2 -q %s 2>&1", addr)); err == nil {
		if m := rttRe.FindStringSubmatch(p.Stdout); len(m) == 2 {
			res.RTTMs, _ = strconv.ParseFloat(m[1], 64)
		}
		if m := lossRe.FindStringSubmatch(p.Stdout); len(m) == 2 {
			res.LossPct, _ = strconv.ParseFloat(m[1], 64)
		}
		res.Raw += "\n\n" + strings.TrimSpace(p.Stdout)
	}

	// 2 KiB through the path, and the kernel's own count of what that took.
	stat, _ := c.lab.Sh(ctx, from, fmt.Sprintf(
		`nstat -n >/dev/null 2>&1; dd if=/dev/zero bs=1024 count=2 2>/dev/null | timeout 4 nc -w 2 %s %s >/dev/null 2>&1; nstat 2>/dev/null | awk '/TcpOutSegs|TcpRetransSegs/ {print $1"="$2}'`,
		addr, port))
	res.Bytes = 2048
	for _, kv := range strings.Fields(stat.Stdout) {
		k, v, _ := strings.Cut(kv, "=")
		n, _ := strconv.Atoi(v)
		switch k {
		case "TcpOutSegs":
			res.Packets = n
		case "TcpRetransSegs":
			res.Retransmits = n
		}
	}
	return res
}

func lastLine(s string) string {
	lines := strings.Split(strings.TrimRight(s, "\n"), "\n")
	return strings.TrimSpace(lines[len(lines)-1])
}

func lastLineContaining(s, want string) string {
	out := ""
	for _, l := range strings.Split(s, "\n") {
		if strings.Contains(l, want) {
			out = strings.TrimSpace(l)
		}
	}
	return out
}

func (c *Controller) ifaceOn(ctx context.Context, id, addr string) string {
	r, err := c.lab.Sh(ctx, id, fmt.Sprintf(`ip -o -4 addr show | awk '$4 ~ /^%s\// {print $2; exit}'`, addr))
	if err != nil {
		return "eth0"
	}
	if s := strings.TrimSpace(r.Stdout); s != "" {
		return s
	}
	return "eth0"
}

