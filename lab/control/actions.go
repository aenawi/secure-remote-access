func (c *Controller) setOnline(ctx context.Context, id string, up bool) Result {
	res := Result{Rung: 1, Rule: id}
	var err error
	if up {
		res.Cmds = []string{"docker compose start " + id}
		err = c.lab.Start(ctx, id)
		res.Why = id + " is running"
	} else {
		res.Cmds = []string{"docker compose stop " + id}
		err = c.lab.Stop(ctx, id)
		res.Why = id + " is stopped — nothing it was doing survives"
	}
	if err != nil {
		res.Why = err.Error()
		return res
	}
	res.OK = true
	c.Observe(ctx)
	return res
}

// evilJoin hands the attacker a working key, or takes it away. This is the
// closest a Headscale lab gets to "somebody leaked a node key".
func (c *Controller) evilJoin(ctx context.Context, join bool) Result {
	res := Result{Rung: 1, Rule: "evil-box"}
	if !c.lab.Running(ctx, "evil-box") {
		res.Why = "evil-box is not running. Start it first — it never starts on its own."
		return res
	}
	if !join {
		res.Cmds = []string{"tailscale logout   # on evil-box"}
		r, _ := c.lab.Exec(ctx, "evil-box", "tailscale", "logout")
		res.OK = true
		res.Raw = r.Out()
		res.Why = "evil-box has no tailnet session any more"
		c.Observe(ctx)
		return res
	}

	s := c.Snapshot()
	if s.ACL.Lock {
		res.OK = false
		res.Rung = 1
		res.Rule = "no key exists for a machine nobody authorised"
		res.Why = "Refused before any policy was consulted. With 'tailnet lock' on, the " +
			"lab never issues a key this machine could present, so no peer will complete " +
			"a handshake with it. Turn lock off and try the same thing again."
		return res
	}
	if c.untrustedKey == "" {
		res.Why = "no spare key was created at boot — try `make reset`"
		return res
	}
	res.Cmds = []string{"tailscale up --login-server=https://headscale:8443 --authkey=tskey-LEAKED   # on evil-box"}
	r, err := c.lab.Exec(ctx, "evil-box", "tailscale", "up",
		"--login-server=https://headscale:8443",
		"--authkey="+c.untrustedKey,
		"--hostname=evil-box", "--accept-routes=false", "--accept-dns=false", "--timeout=30s")
	res.Raw = r.Out()
	if err != nil || r.Code != 0 {
		res.Why = "the join failed: " + r.Out()
		return res
	}
	c.EnsureTags(ctx)
	_ = c.applyPolicy(ctx)
	res.OK = true
	res.Danger = true
	res.Why = "evil-box is on the tailnet. From here the only thing between it and your " +
		"machines is the policy."
	c.Observe(ctx)
	return res
}

// setOnPath puts evil-box in the position a café network puts it in: the router
// lab-ubuntu's traffic leaves through.
func (c *Controller) setOnPath(ctx context.Context, on bool) Result {
	res := Result{Rung: 2, Rule: "lab-ubuntu's default route"}
	if !c.lab.Running(ctx, "evil-box") {
		res.Why = "evil-box is not running."
		return res
	}
	evilLAN := c.lab.IPOn(ctx, "evil-box", "lan-ubuntu")
	if on && evilLAN == "" {
		res.Why = "evil-box is not attached to lab-ubuntu's segment. Start the lab with " +
			"`docker compose --profile attack up -d` so it gets that interface."
		return res
	}

	if on {
		r1, _ := c.lab.Exec(ctx, "evil-box", "lab-onpath", "on")
		r2, err := c.lab.Exec(ctx, "lab-ubuntu", "ip", "route", "replace", "default", "via", evilLAN)
		res.Cmds = []string{
			"lab-onpath on   # on evil-box: ip_forward + masquerade",
			"ip route replace default via " + evilLAN + "   # on lab-ubuntu",
		}
		res.Raw = r1.Out() + "\n" + r2.Out()
		if err != nil {
			res.Why = err.Error()
			return res
		}
		res.OK, res.Danger = true, true
		res.Why = "every packet lab-ubuntu sends now passes through evil-box's kernel. " +
			"It can see all of it."
	} else {
		gw := c.gatewayFor("lab-ubuntu")
		r1, _ := c.lab.Exec(ctx, "lab-ubuntu", "ip", "route", "replace", "default", "via", gw)
		r2, _ := c.lab.Exec(ctx, "evil-box", "lab-onpath", "off")
		res.Cmds = []string{
			"ip route replace default via " + gw + "   # on lab-ubuntu",
			"lab-onpath off   # on evil-box",
		}
		res.Raw = r1.Out() + "\n" + r2.Out()
		res.OK = true
		res.Why = "lab-ubuntu routes through its own NAT again"
	}
	c.with(func(s *State) { s.SegmentShared = on })
	c.saveDesired()
	return res
}

func (c *Controller) gatewayFor(id string) string {
	switch id {
	case "lab-ubuntu":
		return "10.0.13.254"
	case "lab-roam":
		return "10.0.27.254"
	case "evil-box":
		return "10.0.66.254"
	}
	return ""
}

